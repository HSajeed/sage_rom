def check_dmd_lambda_zero_equivalence() -> None:
    """Synthetic exact-linear-operator recovery: a {lin}-only, lambda=0 fit
    on the raw (uncentred) POD basis must reproduce the forward trajectory
    of a known linear map, the same property flowTorch's exact DMD relies
    on (see run_step4a.py's sanity check for the real-data comparison
    against flowTorch's own DMD implementation)."""
    A = pt.tensor([[0.99, 0.20], [-0.20, 0.99]], dtype=pt.float64)   # a rotation-like stable map
    x = pt.tensor([1.0, 0.0], dtype=pt.float64)
    traj = [x]
    for _ in range(40):
        x = A @ x
        traj.append(x)
    X = pt.stack(traj, dim=1)

    basis = pod_basis(X, r=2, center=False)
    Z = project(basis, X)
    library = Library(families=("lin",), extras=())
    D, groups = build_regressors(Z[:, :-1], library)
    coef = fit_ridge(D, Z[:, 1:], 0.0, 0.0, groups)

    traj_pred, diverged, _ = rollout(coef, Z[:, 0], n_steps=X.shape[1] - 1, kind="discrete", library=library)
    X_pred = basis.modes @ traj_pred
    err = (pt.linalg.norm(X_pred - X) / pt.linalg.norm(X)).item()
    check("lambda=0 DMD-equivalence: not diverged", not diverged)
    check("lambda=0 DMD-equivalence: exact linear recovery", err < 1e-8, f"err={err:.2e}")


