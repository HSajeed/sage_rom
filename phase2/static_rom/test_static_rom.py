def _make_quadratic_system_data(n_steps: int, dt: float) -> tuple[pt.Tensor, pt.Tensor, pt.Tensor, pt.Tensor]:
    """A hand-specified 2D quadratic discrete system z_{k+1} = c + A z_k +
    H (z_k (x) z_k)_unique, generated by explicit deterministic formulas
    (no RNG, per project convention). Returns (Z, c, A, H)."""
    c = pt.tensor([0.05, -0.02], dtype=pt.float64)
    A = pt.tensor([[0.9, 0.05], [-0.03, 0.85]], dtype=pt.float64)
    H = pt.tensor([[0.01, -0.02, 0.015], [0.005, 0.01, -0.01]], dtype=pt.float64)  # cols: z1^2, z1z2, z2^2

    def step(z):
        quad = pt.tensor([z[0] * z[0], z[0] * z[1], z[1] * z[1]], dtype=pt.float64)
        return c + A @ z + H @ quad

    z = pt.tensor([1.0, -0.5], dtype=pt.float64)
    traj = [z]
    for _ in range(n_steps):
        z = step(z)
        traj.append(z)
    Z = pt.stack(traj, dim=1)
    return Z, c, A, H


def check_quadratic_discrete_recovery() -> None:
    Z, c_true, A_true, H_true = _make_quadratic_system_data(n_steps=200, dt=0.01)
    library = Library(families=("const", "lin", "quad"), extras=())
    D, groups = build_regressors(Z[:, :-1], library)
    Y = Z[:, 1:]
    coef = fit_ridge(D, Y, 0.0, 0.0, groups)

    c_hat = coef[:, groups["const"]].squeeze(-1)
    A_hat = coef[:, groups["lin"]]
    H_hat = coef[:, groups["quad"]]

    check("quadratic discrete: c recovered", pt.allclose(c_hat, c_true, atol=1e-8),
          f"max|diff|={ (c_hat - c_true).abs().max().item():.2e}")
    check("quadratic discrete: A recovered", pt.allclose(A_hat, A_true, atol=1e-8),
          f"max|diff|={ (A_hat - A_true).abs().max().item():.2e}")
    check("quadratic discrete: H recovered", pt.allclose(H_hat, H_true, atol=1e-8),
          f"max|diff|={ (H_hat - H_true).abs().max().item():.2e}")


def check_quadratic_continuous_recovery() -> None:
    c_true = pt.tensor([0.05, -0.02], dtype=pt.float64)
    A_true = pt.tensor([[-0.8, 0.05], [-0.03, -0.85]], dtype=pt.float64)
    H_true = pt.tensor([[0.01, -0.02, 0.015], [0.005, 0.01, -0.01]], dtype=pt.float64)

    def f(z):
        quad = pt.tensor([z[0] * z[0], z[0] * z[1], z[1] * z[1]], dtype=pt.float64)
        return c_true + A_true @ z + H_true @ quad

    dt = 0.001
    z = pt.tensor([1.0, -0.5], dtype=pt.float64)
    traj = [z]
    for _ in range(400):
        k1 = f(z); k2 = f(z + 0.5 * dt * k1); k3 = f(z + 0.5 * dt * k2); k4 = f(z + dt * k3)
        z = z + (dt / 6.0) * (k1 + 2 * k2 + 2 * k3 + k4)
        traj.append(z)
    Z = pt.stack(traj, dim=1)

    library = Library(families=("const", "lin", "quad"), extras=())
    Z_input, Y, _time_index, trunc = build_target(Z, "continuous", dt)
    D, groups = build_regressors(Z_input, library)
    coef = fit_ridge(D, Y, 0.0, 0.0, groups)

    c_hat = coef[:, groups["const"]].squeeze(-1)
    A_hat = coef[:, groups["lin"]]
    H_hat = coef[:, groups["quad"]]

    check("quadratic continuous: c recovered", (c_hat - c_true).abs().max().item() < 1e-5,
          f"max|diff|={ (c_hat - c_true).abs().max().item():.2e}")
    check("quadratic continuous: A recovered", (A_hat - A_true).abs().max().item() < 1e-4,
          f"max|diff|={ (A_hat - A_true).abs().max().item():.2e}")
    check("quadratic continuous: H recovered", (H_hat - H_true).abs().max().item() < 1e-3,
          f"max|diff|={ (H_hat - H_true).abs().max().item():.2e}")
    check("quadratic continuous: truncation estimate is finite and small",
          math.isfinite(trunc) and trunc < 1.0, f"trunc={trunc:.2e}")


def check_linear_map_recovery() -> None:
    """A pure linear system (no quadratic/const term) recovered by a
    {lin}-only library, lambda=0, via the raw (uncentred) POD basis, in
    the spirit of DMD's exact-recovery-of-a-linear-operator property."""
    A = pt.tensor([
        [0.98, 0.10, 0.0, -0.02],
        [-0.10, 0.98, 0.02, 0.0],
        [0.01, 0.0, 0.95, 0.05],
        [0.0, 0.01, -0.05, 0.95],
    ], dtype=pt.float64)
    x = pt.tensor([1.0, 0.3, -0.4, 0.2], dtype=pt.float64)
    traj = [x]
    for _ in range(60):
        x = A @ x
        traj.append(x)
    X = pt.stack(traj, dim=1)

    basis = pod_basis(X, r=4, center=False)
    Z = project(basis, X)

    library = Library(families=("lin",), extras=())
    D, groups = build_regressors(Z[:, :-1], library)
    Y = Z[:, 1:]
    coef = fit_ridge(D, Y, 0.0, 0.0, groups)

    traj_pred, diverged, _ = rollout(coef, Z[:, 0], n_steps=X.shape[1] - 1, kind="discrete", library=library)
    X_pred = basis.modes @ traj_pred
    err = (pt.linalg.norm(X_pred - X) / pt.linalg.norm(X)).item()
    check("linear map recovery: not diverged", not diverged)
    check("linear map recovery: forecast matches true trajectory", err < 1e-8, f"err={err:.2e}")


